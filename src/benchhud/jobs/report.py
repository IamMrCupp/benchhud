"""Render a repair job + its timeline into a customer-facing report.

The output is Markdown — no dependency, readable as plain text, and trivially
turned into a PDF (any Markdown viewer, or a browser's print-to-PDF). Generation
is a pure function of the job, its notes, and a "generated at" timestamp passed
in, so it's fully deterministic under test — nothing here reads the clock.
"""

from __future__ import annotations

from datetime import datetime

from benchhud.jobs.readings import Row, compare, format_value, mode
from benchhud.jobs.store import Job, JobNote, JobStatus, JobStore

# Human-facing labels for the stored status values.
_STATUS_LABELS = {
    JobStatus.OPEN: "Open",
    JobStatus.IN_PROGRESS: "In progress",
    JobStatus.WAITING: "Waiting (parts / customer)",
    JobStatus.DONE: "Completed",
    JobStatus.SCRAPPED: "Not repairable",
}


def _status_label(status: str) -> str:
    try:
        return _STATUS_LABELS[JobStatus(status)]
    except ValueError:
        return status or "—"


def _humanize_stamp(stamp: str) -> str:
    """ISO-8601 → ``YYYY-MM-DD HH:MM UTC``; pass anything unparseable through."""
    try:
        dt = datetime.fromisoformat(stamp)
    except ValueError:
        return stamp
    offset = dt.utcoffset()
    suffix = " UTC" if offset is not None and offset.total_seconds() == 0 else ""
    return dt.strftime("%Y-%m-%d %H:%M") + suffix


def _attachment_name(path: str) -> str:
    """The bare filename of an attachment, for referencing without a local path."""
    return path.replace("\\", "/").rsplit("/", 1)[-1]


def render_report(
    job: Job,
    notes: list[JobNote],
    *,
    generated_at: str,
    title: str = "Repair Report",
    readings: list[Row] | None = None,
) -> str:
    """Render one job and its note timeline as a Markdown report."""
    lines: list[str] = [f"# {title}", ""]

    # --- details table ---
    rows = [
        ("Device", job.device or "—"),
        ("Serial", job.serial or "—"),
        ("Customer", job.customer or "—"),
        ("Status", _status_label(job.status)),
        ("Opened", _humanize_stamp(job.created_at)),
        ("Last updated", _humanize_stamp(job.updated_at)),
    ]
    if job.external_ref:
        rows.append(("Reference", job.external_ref))
    lines += ["| Field | Detail |", "| --- | --- |"]
    lines += [f"| {field} | {_escape_cell(value)} |" for field, value in rows]
    lines.append("")

    # --- reported symptoms ---
    lines += ["## Reported symptoms", ""]
    lines.append(job.symptoms.strip() or "_None recorded._")
    lines.append("")

    # --- work timeline ---
    lines += ["## Work log", ""]
    if not notes:
        lines.append("_No entries recorded._")
    else:
        for note in notes:
            stamp = _humanize_stamp(note.created_at)
            text = note.text.strip() or "_(no description)_"
            lines.append(f"- **{stamp}** — {text}")
            if note.attachment:
                name = _attachment_name(note.attachment)
                lines.append(f"  - Capture: `{name}`")
    lines.append("")

    # --- measurements (#235): only the points this job measured ---
    measured = [r for r in readings or [] if r.reading is not None]
    if measured:
        lines += ["## Measurements", ""]
        lines += [
            "| Point | Mode | Reading | Known-good | Result |",
            "| --- | --- | --- | --- | --- |",
        ]
        for row in measured:
            found = mode(row.mode)
            unit = found.unit if found else ""
            assert row.reading is not None
            reading = format_value(row.reading.value, row.reading.status, unit)
            if row.reference_count == 0:
                good, result = "—", "—"
            else:
                good = "OL" if row.reference_open else format_value(row.reference, None, unit)
                result = row.verdict.value
            cells = [row.point, found.label if found else row.mode, reading, good, result]
            lines.append("| " + " | ".join(_escape_cell(c) for c in cells) + " |")
        lines.append("")

    # --- footer ---
    lines += ["---", f"_Generated by benchhud on {_humanize_stamp(generated_at)}._", ""]
    return "\n".join(lines)


def _escape_cell(value: str) -> str:
    """Keep a stray ``|`` or newline from breaking the Markdown table."""
    return value.replace("|", "\\|").replace("\n", " ")


def export_report(
    store: JobStore,
    job_id: int,
    *,
    generated_at: str,
) -> str | None:
    """Render the report for ``job_id``; ``None`` if the job doesn't exist."""
    job = store.get_job(job_id)
    if job is None:
        return None
    notes = store.list_notes(job_id)
    references = store.reference_readings(job.board_id or "", exclude_job=job_id)
    readings = compare(store.list_readings(job_id), references)
    return render_report(job, notes, generated_at=generated_at, readings=readings)
